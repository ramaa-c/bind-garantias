export function parseTerminos(text) {
  if (!text) return [];

  const sections = [];
  let currentSection = {
    id: "intro_texto",
    titulo: null,
    parrafos: [],
    esTabla: false,
    tableRows: []
  };

  const lines = text.split("\n");
  let inTable = false;

  for (let i = 0; i < lines.length; i++) {
    const line = lines[i].trim();
    if (!line) continue;

    if (line.startsWith("## ")) {
      // Guardar sección anterior si tiene contenido
      if (currentSection.parrafos.length > 0 || currentSection.tableRows.length > 0) {
        sections.push(currentSection);
      }
      const title = line.replace("## ", "").trim();
      const id = title.toLowerCase()
        .replace(/[^a-z0-9]+/g, "_")
        .replace(/^_+|_+$/g, "");
      currentSection = {
        id,
        titulo: title,
        parrafos: [],
        esTabla: false,
        tableRows: []
      };
      inTable = false;
    } else if (line.includes(" | ") || (line.includes("|") && !line.includes("||"))) {
      // Si veníamos de párrafos en la sección actual, guardarla primero para separar tabla
      if (currentSection.parrafos.length > 0 && !currentSection.esTabla) {
        sections.push(currentSection);
        currentSection = {
          id: "intro_tabla_" + i,
          titulo: null,
          parrafos: [],
          esTabla: true,
          tableRows: []
        };
      }
      currentSection.esTabla = true;
      inTable = true;
      const parts = line.split("|").map(p => p.trim());
      if (parts.length >= 2) {
        currentSection.tableRows.push({
          term: parts[0],
          definition: parts[1]
        });
      }
    } else {
      if (inTable) {
        if (currentSection.tableRows.length > 0) {
          sections.push(currentSection);
        }
        currentSection = {
          id: "seccion_parrafo_" + i,
          titulo: null,
          parrafos: [],
          esTabla: false,
          tableRows: []
        };
        inTable = false;
      }
      currentSection.parrafos.push(line);
    }
  }

  if (currentSection.parrafos.length > 0 || currentSection.tableRows.length > 0) {
    sections.push(currentSection);
  }

  return sections;
}
